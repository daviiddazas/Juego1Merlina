/**
 * Shuffles an array in place using Fisher-Yates and returns a fresh copy
 */
export function shuffleArray<T>(array: T[]): T[] {
  const result = [...array];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

/**
 * Generates questions with randomized/shuffled option order and assigned letters (A, B, C, D...)
 * Filters/samples options to maintain a balanced selection of Addams Family and Nevermore characters!
 */
export function generateShuffledQuestions(): QuizQuestion[] {
  const letters = ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H', 'I', 'J'];

  return QUIZ_QUESTIONS_RAW.map((q) => {
    // Shuffle the options so they never appear in predictable order
    const shuffled = shuffleArray(q.options);

    // Assign dynamic letters based on shuffled position
    const optionsWithLetters = shuffled.map((opt, idx) => ({
      ...opt,
      letter: letters[idx] || `${idx + 1}`,
    }));

    return {
      ...q,
      options: optionsWithLetters,
    };
  });
}

